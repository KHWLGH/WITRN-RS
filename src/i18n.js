/** @type {Record<ResolvedLanguage, Record<string, string>>} */
export const dictionaries = { 'zh-CN': ZH_CN, 'zh-TW': ZH_TW, en: EN, ja: JA };
for (const [key, translations] of Object.entries(messages)) {
  for (const [index, language] of ['en', 'zh-CN', 'zh-TW', 'ja'].entries()) {
    dictionaries[language][key] = translations[index];
  }
}

/** @param {unknown} value @returns {LanguagePreference} */
export function normalizeLanguagePreference(value) {
  return LANGUAGE_PREFERENCES.includes(/** @type {any} */ (value)) ? /** @type {LanguagePreference} */ (value) : 'auto';
}

/** @param {string|undefined|null} locale @returns {ResolvedLanguage} */
export function resolveLocale(locale) {
  const raw = String(locale ?? '')
    .trim()
    .replace(/_/g, '-');
  const base = raw.split(/[.@]/, 1)[0];
  if (!base || /^c$/i.test(base) || /^posix$/i.test(base)) return 'en';
  if (!/^[a-z]{2,3}(?:-[a-z0-9]{2,8})*$/i.test(base)) return 'en';
  const [language, ...parts] = base.toLowerCase().split('-');
  if (language === 'ja') return 'ja';
  if (language === 'zh') {
    if (parts.includes('hans')) return 'zh-CN';
    if (parts.includes('hant')) return 'zh-TW';
    return parts.some((part) => ['tw', 'hk', 'mo'].includes(part)) ? 'zh-TW' : 'zh-CN';
  }
  return 'en';
}

function updateLanguageSelector() {
  const select = typeof document !== 'undefined' ? document.getElementById('language-select') : null;
  if (typeof HTMLSelectElement === 'undefined' || !(select instanceof HTMLSelectElement)) return;
  const auto = select.querySelector('option[value="auto"]');
  if (auto) {
    const name = { 'zh-CN': '简体中文', 'zh-TW': '繁體中文', en: 'English', ja: '日本語' }[resolvedLanguage];
    auto.textContent = `${t('followSystem')} (${name})`;
  }
  select.value = normalizeLanguagePreference(state.settings.language);
  select.setAttribute('aria-label', t('language'));
}

/** @param {LanguagePreference} preference @param {string|undefined|null} systemLocale */
export function resolveLanguage(preference, systemLocale) {
  const normalized = normalizeLanguagePreference(preference);
  return normalized === 'auto' ? resolveLocale(systemLocale) : normalized;
}

let resolvedLanguage = /** @type {ResolvedLanguage} */ ('en');
let systemLocale = '';
/** @type {Set<(language: ResolvedLanguage) => void>} */
const listeners = new Set();

/** @param {string} key @param {Record<string, unknown>} [params] @returns {string} */
export function t(key, params = {}) {
  const dict = dictionaries[resolvedLanguage] ?? EN;
  if (Number(params.count) === 1 && Object.hasOwn(EN, `${key}One`)) key = `${key}One`;
  const text = (Object.hasOwn(dict, key) ? dict[key] : undefined) ?? (Object.hasOwn(EN, key) ? EN[key] : key);
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

