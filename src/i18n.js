/** @param {(language: ResolvedLanguage) => void} listener @returns {() => void} */
export function onLanguageChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** Translate marked text nodes and attributes without replacing interactive elements. */
export function translateDocument(root = typeof document !== 'undefined' ? document : null) {
  if (!root) return;
  for (const el of root.querySelectorAll?.('[data-i18n]') ?? []) {
    el.textContent = t(el.getAttribute('data-i18n') ?? '');
  }
  for (const attr of ['title', 'placeholder', 'aria-label', 'alt']) {
    for (const el of root.querySelectorAll?.('[data-i18n-' + attr + ']') ?? []) {
      el.setAttribute(attr, t(el.getAttribute('data-i18n-' + attr) ?? ''));
    }
  }
  if (typeof document !== 'undefined') document.documentElement?.setAttribute('lang', resolvedLanguage);
}

/** Describe structured application errors while preserving external plugin strings. */
/** @param {unknown} error @returns {string} */
export function errorText(error) {
  const message = /** @type {{code?: string, params?: Record<string, unknown>, detail?: string}|null} */ (error);
  if (message && typeof message === 'object' && typeof message.code === 'string') {
    if (!Object.hasOwn(EN, message.code)) return t('operationFailed', { detail: message.detail || message.code });
    const params = { ...message.params, detail: message.detail ?? message.params?.detail ?? '' };
    return t(message.code, params);
  }
  const text = error instanceof Error ? error.message : String(error ?? '');
  return Object.hasOwn(EN, text) ? t(text) : text;
}

/** @param {LanguagePreference} preference @param {{systemLocale?: string}} [options] */
export async function applyLanguage(preference, options = {}) {
  const normalized = normalizeLanguagePreference(preference);
  if (options.systemLocale !== undefined) systemLocale = options.systemLocale;
  const browserLocale = typeof navigator !== 'undefined' ? navigator.languages?.[0] || navigator.language : '';
  resolvedLanguage = resolveLanguage(normalized, systemLocale || browserLocale);
  state.settings.language = normalized;
  translateDocument();
  updateLanguageSelector();
  for (const listener of listeners) listener(resolvedLanguage);
  if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
    const EventCtor = typeof CustomEvent === 'function' ? CustomEvent : null;
    if (EventCtor)
      window.dispatchEvent(
        new EventCtor('lapower:language-changed', { detail: { language: resolvedLanguage, preference: normalized } }),
      );
  }
  return resolvedLanguage;
}

/** Resolve the native locale before the rest of the UI is initialised. */
export async function initI18n() {
  let native = '';
  try {
    native = String(
      (typeof window !== 'undefined' ? await window.__TAURI__?.core?.invoke('get_system_locale') : '') ?? '',
    ).trim();
  } catch {
    native = '';
  }
  systemLocale =
    native || (typeof navigator !== 'undefined' ? navigator.languages?.[0] || navigator.language : '') || '';
  await applyLanguage(normalizeLanguagePreference(state.settings.language), { systemLocale });
  return resolvedLanguage;
}
